#!/usr/bin/env bash
# Automated QC of the delivered episodes -> docs/QC_REPORT.md
# format, codec, size, fps, duration, full decode (errors), first-frame not black, black/frozen segments, loudness + true peak.
cd "$(dirname "$0")/.."
R=docs/QC_REPORT.md
{
echo "# SOMEONE IS IN THE POOL — QC report"
echo
echo "Generated by \`tools/qc.sh\` on $(date -u +'%Y-%m-%d %H:%M UTC')."
for N in 1 2 3; do
  F=deliverables/SOMEONE_IS_IN_THE_POOL_NIGHT_0$N.mp4
  echo; echo "## NIGHT 0$N — \`$(basename $F)\`"
  if [[ ! -s $F ]]; then echo "**MISSING**"; continue; fi
  echo; echo '```'
  ffprobe -v error -show_entries format=duration,size,bit_rate:stream=codec_name,profile,width,height,pix_fmt,r_frame_rate,avg_frame_rate,sample_rate,channels -of default=nw=1 $F
  echo "sha256: $(sha256sum $F | cut -c1-64)"
  errs=$(ffmpeg -v error -i $F -f null - 2>&1 | wc -l); echo "full decode errors: $errs"
  ffmpeg -v error -i $F -frames:v 1 -vf "signalstats,metadata=print:key=lavfi.signalstats.YAVG" -f null - 2>&1 | grep -o "YAVG=[0-9.]*" | sed 's/^/first frame luma /'
  echo "black segments (>0.25 s):"; ffmpeg -i $F -vf "blackdetect=d=0.25:pic_th=0.97" -an -f null - 2>&1 | grep -o "black_start:[0-9.]* black_end:[0-9.]* black_duration:[0-9.]*" | sed 's/^/  /'
  echo "frozen segments (>2.5 s):"; ffmpeg -i $F -vf "freezedetect=n=0.003:d=2.5" -an -f null - 2>&1 | grep -oE "freeze_(start|end): [0-9.]*" | paste - - | sed 's/^/  /'
  echo "loudness:"; ffmpeg -nostats -i $F -af ebur128=peak=true -f null - 2>&1 | grep -E "^\s+(I|Peak|LRA):" | tail -3 | sed 's/^ */  /'
  echo '```'
done
} > $R
cat $R
